// 去掉 0/O、1/I/l 等易混淆字符。
var captchaChars = []byte("23456789ABCDEFGHJKLMNPQRSTUVWXYZ")

// secureRandInt 返回 [0,n) 内的密码学随机整数；失败时返回 error，由调用方决定如何处理。
func secureRandInt(n int) (int, error) {
	if n <= 0 {
		return 0, nil
	}
	v, err := rand.Int(rand.Reader, big.NewInt(int64(n)))
	if err != nil {
		return 0, err
	}
	return int(v.Int64()), nil
}

// cryptoRandInt 用于非安全敏感的验证码图片噪点，随机源失败时退化为 0 无安全影响。
func cryptoRandInt(n int) int {
	v, _ := secureRandInt(n)
	return v
}

func randomCaptchaText(n int) (string, error) {
	var b strings.Builder
	for i := 0; i < n; i++ {
		v, err := secureRandInt(len(captchaChars))
		if err != nil {
			return "", err
		}
		b.WriteByte(captchaChars[v])
	}
	return b.String(), nil
}

// generateCaptchaImage 生成带干扰线与噪点的 PNG 验证码，返回 data URL。
func generateCaptchaImage(text string) (string, error) {
	const scale = 3
	const charW = 5 * scale
	const charH = 7 * scale
	const gap = 7
	const padX = 10
	const padY = 8

	width := padX*2 + len(text)*(charW+gap) - gap
	height := padY*2 + charH
	img := image.NewRGBA(image.Rect(0, 0, width, height))
	draw.Draw(img, img.Bounds(), &image.Uniform{C: color.RGBA{248, 250, 252, 255}}, image.Point{}, draw.Src)

	for i := 0; i < len(text); i++ {
		glyph, ok := captchaFont[text[i]]
		if !ok {
			continue
		}
		c := color.RGBA{uint8(20 + cryptoRandInt(110)), uint8(20 + cryptoRandInt(110)), uint8(20 + cryptoRandInt(110)), 255}
		ox := padX + i*(charW+gap)
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if glyph[row]&(1<<uint(4-col)) == 0 {
					continue
				}
				for sy := 0; sy < scale; sy++ {
					for sx := 0; sx < scale; sx++ {
						img.Set(ox+col*scale+sx, padY+row*scale+sy, c)
					}
				}
			}
		}
	}

	for i := 0; i < 3; i++ {
		c := color.RGBA{uint8(120 + cryptoRandInt(120)), uint8(120 + cryptoRandInt(120)), uint8(120 + cryptoRandInt(120)), 200}
		drawCaptchaLine(img,
			cryptoRandInt(width), cryptoRandInt(height),
			cryptoRandInt(width), cryptoRandInt(height), c)
	}
	for i := 0; i < 45; i++ {
		img.Set(cryptoRandInt(width), cryptoRandInt(height), color.RGBA{150, 150, 170, 255})
	}

	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		return "", err
	}
	return "data:image/png;base64," + base64.StdEncoding.EncodeToString(buf.Bytes()), nil
}

func drawCaptchaLine(img *image.RGBA, x0, y0, x1, y1 int, c color.Color) {
	dx, dy := absInt(x1-x0), absInt(y1-y0)
	sx, sy := 1, 1
	if x0 > x1 {
		sx = -1
	}
	if y0 > y1 {
		sy = -1
	}
	err := dx - dy
	for {
		if x0 >= 0 && y0 >= 0 && x0 < img.Bounds().Dx() && y0 < img.Bounds().Dy() {
			img.Set(x0, y0, c)
		}
		if x0 == x1 && y0 == y1 {
			break
		}
		e2 := 2 * err
		if e2 > -dy {
			err -= dy
			x0 += sx
		}
		if e2 < dx {
			err += dx
			y0 += sy
		}
	}
}

func absInt(v int) int {
	if v < 0 {
		return -v
	}
	return v
}
